-- Esquema mínimo que imita Supabase para probar la migración 002 en un
-- Postgres local. Solo contiene lo que la migración y sus pruebas necesitan.

-- Roles de Supabase. service_role ignora RLS, como en Supabase.
create role anon nologin;
create role authenticated nologin;
create role service_role nologin bypassrls;
grant usage on schema public to anon, authenticated, service_role;

-- Esquema auth: solo las columnas que usa la migración.
create schema auth;
grant usage on schema auth to anon, authenticated, service_role;

create table auth.users (
  id uuid primary key,
  raw_user_meta_data jsonb
);

create table auth.identities (
  user_id uuid references auth.users (id) on delete cascade,
  provider text,
  identity_data jsonb
);

create function auth.uid() returns uuid
language sql stable
as $$ select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid $$;

-- Tablas públicas existentes (esquema real conocido).
create table public.stores (
  id integer primary key,
  slug text unique not null,
  name text not null,
  website text
);

create table public.products (
  id integer generated by default as identity primary key,
  store_id integer not null references public.stores (id),
  name text not null,
  url text not null,
  category text not null check (category in ('cpu', 'gpu', 'ram')),
  price integer,
  in_stock boolean,
  price_updated_at timestamptz,
  last_seen_at timestamptz,
  unique (store_id, url)
);

create table public.price_history (
  id bigint generated by default as identity primary key,
  product_id integer references public.products (id) on delete cascade,
  price integer,
  in_stock boolean,
  scraped_at timestamptz default now()
);

create table public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  display_name text,
  language text
);

-- product_reviews antes de la migración: por producto de tienda y con una
-- política vieja abierta que la migración debe eliminar.
create table public.product_reviews (
  id bigint generated by default as identity primary key,
  product_id integer references public.products (id),
  user_id uuid,
  rating int,
  comment text,
  created_at timestamptz
);

alter table public.stores enable row level security;
alter table public.products enable row level security;
alter table public.price_history enable row level security;
alter table public.profiles enable row level security;
alter table public.product_reviews enable row level security;

create policy stores_read on public.stores for select to anon, authenticated using (true);
create policy products_read on public.products for select to anon, authenticated using (true);
create policy price_history_read on public.price_history for select to anon, authenticated using (true);
-- profiles es privada en la base real: cada usuario ve solo la suya.
create policy profiles_read_own on public.profiles for select to authenticated using (id = auth.uid());
create policy old_open on public.product_reviews for all using (true);

grant select on public.stores, public.products, public.price_history to anon, authenticated;
grant select on public.profiles to authenticated;
-- Como los permisos por defecto de Supabase: product_reviews abierta a nivel de grants.
grant select, insert, update, delete on public.product_reviews to anon, authenticated;
-- service_role (clave secreta) puede todo sobre las tablas existentes.
grant all on all tables in schema public to service_role;
grant usage, select on all sequences in schema public to service_role;
